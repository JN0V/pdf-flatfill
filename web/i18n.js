export let lang = (() => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && translations[saved]) return saved;
  } catch { /* storage unavailable: detection only */ }
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return translations[nav] ? nav : 'en';
})();

export function t(key, vars) {
  let str = translations[lang][key] ?? translations.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.replace(`{${k}}`, v);
  return str;
}

// n units, correctly pluralized: "2 textes", "1 check", "3 Bilder".
// Languages with more than two plural forms (e.g. Russian) provide
// `<unit>_<category>` keys resolved through Intl.PluralRules; the rest
// fall back to the binary `<unit>1` / `<unit>N` pair.
export function tn(n, unit) {
  const dict = translations[lang];
  const category = new Intl.PluralRules(lang).select(n);
  const word = dict[`${unit}_${category}`]
    ?? dict[n > 1 ? `${unit}N` : `${unit}1`]
    ?? translations.en[n > 1 ? `${unit}N` : `${unit}1`];
  return `${n} ${word}`;
}

export function setLang(next) {
  if (!translations[next]) return;
  lang = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* too bad */ }
  applyStatic();
}

// Translates all static HTML: text, placeholders, aria-labels.
export function applyStatic() {
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL.has(lang) ? 'rtl' : 'ltr';
  document.title = `pdf-flatfill — ${t('title')}`;
  for (const el of document.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of document.querySelectorAll('[data-i18n-ph]')) {
    el.placeholder = t(el.dataset.i18nPh);
  }
  for (const el of document.querySelectorAll('[data-i18n-aria]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
    el.title = t(el.dataset.i18nAria);
  }
  for (const select of document.querySelectorAll('.lang-select')) {
    if (!select.options.length) {
      for (const [code, name] of Object.entries(LANGS)) select.add(new Option(name, code));
    }
    select.value = lang;
  }
}
